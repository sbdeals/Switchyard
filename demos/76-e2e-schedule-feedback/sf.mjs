// Schedule Run-now feedback demo on a not-running throwaway app.
import { open, login } from './lib.mjs';
import fs from 'fs'; import { execSync } from 'child_process';
const [label, out] = process.argv.slice(2); const APP = process.env.APP || 'nginx-g9se';
fs.mkdirSync(out, { recursive: true });
const vdir = `${out}/video-${label}`; fs.rmSync(vdir, { recursive: true, force: true });
const { browser, ctx, page } = await open({ video: vdir });
const log = []; const drawer = () => page.locator('[role=dialog]').last();
await login(page); await page.waitForTimeout(1500);
await page.getByText(APP, { exact: true }).first().click(); await page.waitForTimeout(1200);
await page.getByRole('tab', { name: 'Schedules' }).click(); await page.waitForTimeout(1200);
await page.getByPlaceholder('nightly-backup').fill('demo-run-now'); await page.getByPlaceholder('0 3 * * *').fill('0 0 1 1 *');
await page.getByPlaceholder('node scripts/cleanup.js').fill('printf e2e-019'); await page.getByRole('button', { name: 'Create' }).click(); await page.waitForTimeout(2500);
const run = drawer().locator('button[title="Run now"], button[title^="Start the service"]').first();
const t = await run.getAttribute('title'); const dis = await run.isDisabled();
log.push(`Run now button: title=${JSON.stringify(t)} disabled=${dis}`);
await run.hover(); await page.waitForTimeout(1200);
const before = await drawer().innerText();
await run.click({ force: true, timeout: 3000 }).catch(e => log.push('click: ' + e.message.split('\n')[0]));
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/${label}-run-now.png` });
const after = await drawer().innerText();
const newText = after.split('\n').filter(l => l.trim() && !before.split('\n').includes(l));
log.push(`text after clicking Run now: ${JSON.stringify(newText.slice(0, 8))}`);
const hist = execSync(`sudo docker exec dokploy-postgres psql -U dokploy -d dokploy -Atc "select d.status, d.\\"errorMessage\\" from deployment d join schedule s on s.\\"scheduleId\\"=d.\\"scheduleId\\" where s.name='demo-run-now'"`).toString().trim();
log.push(`Dokploy schedule executions: ${hist || '(none)'}`);
await ctx.close(); await browser.close();
const v = fs.readdirSync(vdir).find(f => f.endsWith('.webm')); fs.renameSync(`${vdir}/${v}`, `${out}/${label}.webm`); fs.rmSync(vdir, { recursive: true });
execSync(`ffmpeg -loglevel error -y -i ${out}/${label}.webm -c:v libx264 -pix_fmt yuv420p -movflags +faststart ${out}/${label}.mp4 && rm ${out}/${label}.webm`);
fs.writeFileSync(`${out}/${label}.txt`, log.join('\n') + '\n'); console.log(log.join('\n'));
