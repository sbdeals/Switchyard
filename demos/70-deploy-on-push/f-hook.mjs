// F demo: Settings > Deploy on push > Enable, then send a signed GitHub push to the hook, then check the Deploys row.
import { open, login } from './lib.mjs';
import crypto from 'node:crypto';
const BASE = process.env.BASE, OUT = process.env.OUT || '/tmp/fdemo', APP = process.env.APP || 'nodejs-getting-started';
const { browser, page, context } = await open({ video: OUT }); await login(page); await page.waitForTimeout(2500);
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
await page.getByText(new RegExp(APP)).first().click(); await page.waitForTimeout(1500);
await page.getByRole('tab', { name: 'Settings' }).click(); await page.waitForTimeout(1500);
await shot('1-settings-disabled');
const en = page.locator('button', { hasText: /^Enable$/ }); if (await en.count()) await en.last().click(); else console.log('(already enabled)'); await page.waitForTimeout(3000);
const dlg = page.getByRole('dialog').first();
const panelText = await dlg.innerText(); console.log('--- panel after enable ---\n' + panelText.split('Danger zone')[0].split('Deploy on push').slice(1).join('Deploy on push'));
const vals = await dlg.locator('input, code').evaluateAll(els => els.map(e => e.value ?? e.textContent));
const url = vals.find(v => /\/api\/hooks\/deploy\/[0-9a-f]{64}/.test(v || '')) || (panelText.match(/https?:\S*\/api\/hooks\/deploy\/[0-9a-f]{64}/) || [])[0];
const secret = vals.find(v => /^[A-Za-z0-9_\-]{24,}$/.test(v || '') && !/hooks/.test(v));
console.log('hook url found:', !!url, '| secret shown:', !!secret);
await shot('2-settings-enabled');
const path = new URL(url).pathname;
const sha = crypto.randomBytes(20).toString('hex');
const body = JSON.stringify({ ref: 'refs/heads/main', after: sha, deleted: false, head_commit: { id: sha, message: 'demo: push-to-deploy from Switchyard F proof\n\nbody' } });
const sig = 'sha256=' + crypto.createHmac('sha256', secret).update(body).digest('hex');
const post = async (h, b = body) => { const r = await fetch(BASE + path, { method: 'POST', headers: { 'content-type': 'application/json', 'x-github-event': 'push', ...h }, body: b }); return `${r.status} ${(await r.text()).slice(0, 120)}`; };
console.log('unsigned      ->', await post({}));
console.log('bad signature ->', await post({ 'x-hub-signature-256': 'sha256=' + '0'.repeat(64) }));
console.log('signed push   ->', await post({ 'x-hub-signature-256': sig }));
console.log('duplicate     ->', await post({ 'x-hub-signature-256': sig }));
await page.waitForTimeout(4000);
await page.getByRole('tab', { name: 'Deploys' }).click(); await page.waitForTimeout(4000);
const dep = await page.getByRole('dialog').first().innerText();
console.log('newest deploy row:', (dep.match(/Deploy [0-9a-f]{7} · [^\n]+\n[^\n]+/) || ['none'])[0].replace('\n', ' | '), '(Dokploy builds the real branch HEAD, so the row shows the real commit, not the payload sha)');
console.log('--- deploys (head) ---\n' + dep.split('Deploys').slice(2).join('Deploys').slice(0, 500));
await shot('3-deploys-row');
await page.close(); await browser.close();
