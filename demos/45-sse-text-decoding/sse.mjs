import { open, login } from './lib.mjs';
import fs from 'fs';
import { execSync } from 'child_process';
const [label, out, cname] = process.argv.slice(2);
const vdir = `${out}/video-${label}`; fs.rmSync(vdir, { recursive: true, force: true });
const { browser, ctx, page } = await open({ video: vdir });
await page.setContent(`<body style="background:#0b0b10;color:#e5e5e5;font:20px ui-monospace,monospace;padding:40px"><h2 style="color:#a78bfa">[${label}] Logs tab across a container restart</h2><p>Container prints "=== container started ===" and tick 1..5, then idles.</p><p>We open Logs, then run <b>docker restart</b>. The log stream ends and the browser's EventSource reconnects, and the server replays the last 300 lines.</p><p>Expected: one clean copy of the history. Bug: the old lines are duplicated after every reconnect.</p></body>`);
await page.waitForTimeout(4000);
await login(page); await page.waitForTimeout(2000);
await page.getByText('registry-app', { exact: true }).first().click(); await page.waitForTimeout(1200);
await page.getByText('Logs', { exact: true }).first().click(); await page.waitForTimeout(4000);
await page.screenshot({ path: `${out}/${label}-1-initial.png` });
execSync(`docker restart -t 1 ${cname}`);
await page.waitForTimeout(14000);
await page.screenshot({ path: `${out}/${label}-2-after-restart.png` });
const text = await page.locator('[aria-label="Service logs"]').innerText().catch(() => page.locator('body').innerText());
await ctx.close(); await browser.close();
const v = fs.readdirSync(vdir).find(f => f.endsWith('.webm')); fs.renameSync(`${vdir}/${v}`, `${out}/${label}.webm`); fs.rmSync(vdir, { recursive: true });
fs.writeFileSync(`${out}/${label}-logs.txt`, text);
const n = (text.match(/tick 1 /g) || []).length, s = (text.match(/container started/g) || []).length;
console.log(`${label}: occurrences of "tick 1": ${n}; "container started": ${s}`);
